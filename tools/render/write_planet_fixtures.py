"""Write ARMPLN01 fixtures for the native planet codec test.

Two encoders that each round-trip through themselves can still disagree, so the native test loads
these bytes, checks every field, re-encodes and compares byte for byte.
"""
from __future__ import annotations

import argparse
import pathlib
import struct
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[2]))

from render_bridge import planets  # noqa: E402


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--out', default='render_cpp/tests/fixtures/planets')
    args = parser.parse_args()
    out = pathlib.Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    # A 4x4 RGBA texture: small enough to read in a hex dump, with a recognisable pattern.
    pixels = bytearray()
    for y in range(4):
        for x in range(4):
            pixels += bytes(((x * 60) % 256, (y * 60) % 256, (x + y) * 20 % 256, 255))
    body = bytes(pixels)
    (out / 'temperate.bin').write_bytes(
        planets.encode_blob('p1-3500', 4, 4, body))

    # Same blob with one byte of the payload flipped: the crc must catch it.
    corrupt = bytearray((out / 'temperate.bin').read_bytes())
    corrupt[-8] ^= 0xFF
    (out / 'bad-crc.bin').write_bytes(bytes(corrupt))

    # Wrong length, wrong magic, and a zero dimension.
    wrong_length = (out / 'temperate.bin').read_bytes()[:-4]
    (out / 'bad-length.bin').write_bytes(wrong_length)
    wrong_magic = bytearray((out / 'temperate.bin').read_bytes())
    wrong_magic[0:8] = b'ARMXXX01'
    (out / 'bad-magic.bin').write_bytes(bytes(wrong_magic))
    header = list(struct.unpack_from('<8sHHHHI', (out / 'temperate.bin').read_bytes()))
    header[2] = 0
    (out / 'bad-size.bin').write_bytes(
        struct.pack('<8sHHHHI', header[0], header[1], 0, header[3], header[4], header[5])
        + (out / 'temperate.bin').read_bytes()[20:])

    (out / 'README.txt').write_text(
        'Generated by tools/render/write_planet_fixtures.py -- do not edit by hand.\n'
        'temperate.bin is a 4x4 RGBA ARMPLN01 blob named p1-3500; the bad-* files must be refused.\n',
        encoding='utf-8')
    print(f'{out}: {len(list(out.glob("*.bin")))} blobs')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
