"""S06 batch B5 guards - the shared asteroid prop, the batch's one mesh row.

The environment rows are four asset classes, not thirteen meshes (`art/manifests/handoffs/S06-B5-SCOPE.md`,
generated by `tools/art/probe_b5_scope.py`), and the owner adopted the recommendation that B5 author
only the row that is geometry: `environment:asteroid_field`, drawn forty times per field by
`render/renderer.py::_draw_asteroid_field`.

The prop is a *unit* rock - the field scales it - so the guards below pin four things beyond the usual
mesh contract: that the prop reaches and never exceeds the extent the legacy rock can reach at scale
1.0, that the drawing seam leaves the legacy fallback reachable, that the field's own geometry and
gameplay values are untouched, and that **both drawing paths consume the identical RNG stream**, which
is what makes a before/after capture an isolated change of shape rather than a rearranged field.

Run:  PYTHONPATH=tests .venv/bin/python -m unittest test_alliance_blender_b5_asteroid
"""

import ast
import json
import math
import random
import re
import unittest
from pathlib import Path
from types import SimpleNamespace

ROOT = Path(__file__).resolve().parents[1]
PENDING = ROOT / 'art/manifests/pending'
SPEC = PENDING / 'S06-BATCH-B5-ENVIRONMENT.json'
SIDECAR = PENDING / 'S06-SHARED-ASTEROID-FIELD.json'
SEED = 'tools/art/build_b5_asteroid.py'
RENDERER = ROOT / 'render/renderer.py'
BINDING = 'environment:asteroid_field'
IDENTIFIER = 'shared_asteroid_field'
ENVELOPE = ((-0.58, 0.58), (-0.46, 0.46), (-0.58, 0.58))
MIN_LENGTH = 1.0
# The legacy rock's worst-case reach, kept as a ceiling the prop must never cross.
CEILING = ((-0.90, 0.90), (-0.70, 0.70), (-0.90, 0.90))
# A declared small prop (owner decision `s06-small-prop-class-2026-10-17`): 120 triangles of floor
# instead of 1,800, because the renderer draws it forty times per field, and its own tight ceiling.
# The owner's appearance decision for this row (`s06-b5-environment-2026-10-17`). Appearance only:
# the row is not registered, not selectable and not activated by it.
APPEARANCE_DECISION = 's06-b5-environment-2026-10-17'
BATCH_STATUS = 'appearance_approved_pending_landing'
CLASS_FLOOR = 120
OWN_CAPS = dict(triangles=600, vertices=500, bytes=120_000)
LOADER_CAPS = dict(triangles=12000, vertices=10000, bytes=2_000_000)
ROLES = ('base', 'dark', 'trim', 'accent', 'lit', 'cool')
# The legacy rock's own geometry, quoted so the guard can compare against it rather than trust the
# refactor: 3-5 sub-rocks, 8 corner + 6 bulge radii each, 24 triangles per sub-rock.
LEGACY_DRAWS = dict(colour=3, count=1, jitter=3, first_size=1, radii=14)


def load(path):
    return json.loads(Path(path).read_text(encoding='utf-8'))


def renderer_source():
    return RENDERER.read_text(encoding='utf-8')


def mesh():
    return load(ROOT / f'assets/models/{IDENTIFIER}.mesh.json')


def function_source(name):
    """One function's source text, so a guard can read what it calls without a GL context."""
    text = renderer_source()
    match = re.search(rf'^(?:    )?def {name}\(', text, re.M)
    assert match, name
    start = match.start()
    indent = '    ' if text[start:start + 4] == '    ' else ''
    body = [text[start:].splitlines()[0]]
    for line in text[start:].splitlines()[1:]:
        if line.strip() and not line.startswith(indent + (' ' if indent else '')):
            break
        body.append(line)
    return '\n'.join(body)


class PropContract(unittest.TestCase):
    def test_the_prop_satisfies_the_loader_contract_and_its_own_caps(self):
        data = mesh()
        self.assertEqual(data['asset'], IDENTIFIER)
        self.assertEqual(data['triangle_count'], sum(len(v) for v in data['batches'].values()))
        self.assertGreater(data['triangle_count'], CLASS_FLOOR,
                           'the exporter refuses at or under the class floor')
        self.assertLessEqual(data['triangle_count'], OWN_CAPS['triangles'])
        self.assertLessEqual(len(data['vertices']), OWN_CAPS['vertices'])
        self.assertLessEqual(SIDECAR.stat().st_size, OWN_CAPS['bytes'] + 400_000)
        self.assertLessEqual(data['triangle_count'], LOADER_CAPS['triangles'])
        self.assertLessEqual(len(data['vertices']), LOADER_CAPS['vertices'])
        for role, rows in data['batches'].items():
            self.assertIn(role, ROLES)
            for row in rows:
                self.assertEqual(len(row), 6)
                for index in row[3:]:
                    self.assertLess(index, len(data['vertices']))
                self.assertAlmostEqual(math.sqrt(sum(c * c for c in row[:3])), 1.0, places=9)
        self.assertEqual({r for r, rows in data['batches'].items() if rows}, set(ROLES),
                         'every loader role has to be filled by real geometry')

    def test_the_prop_reaches_the_legacy_rock_box_and_exceeds_it_nowhere(self):
        """The prop is a unit rock, so its box is what the legacy rock can reach at scale 1.0."""
        lo, hi = mesh()['bounds']
        for axis in range(3):
            low, high = ENVELOPE[axis]
            self.assertLessEqual(abs(lo[axis] - low), max(1e-3, abs(low) * .01),
                                 f'axis {axis} low {lo[axis]} does not reach {low}')
            self.assertLessEqual(abs(hi[axis] - high), max(1e-3, abs(high) * .01),
                                 f'axis {axis} high {hi[axis]} does not reach {high}')
        self.assertGreaterEqual(hi[2] - lo[2], MIN_LENGTH)

    def test_the_prop_is_a_unit_rock_because_the_field_scales_it(self):
        body = function_source('_draw_rock')
        self.assertIn('glScalef(s, s, s)', body,
                      'the prop is unit scale and the instance scale is applied at draw time')
        self.assertLessEqual(max(abs(v) for pair in ENVELOPE for v in pair), 0.58)

    def test_the_recipe_refuses_to_overwrite_an_existing_master(self):
        text = (ROOT / SEED).read_text(encoding='utf-8')
        self.assertIn('is the editable master', text)
        self.assertIn("'--replace-seed' not in argv", text)
        self.assertLess(text.index('_refuse_existing_master(_ARGV)'), text.index('import bpy'))

    def test_the_seed_extent_check_catches_a_real_overrun_and_ignores_float_noise(self):
        tree = ast.parse((ROOT / SEED).read_text(encoding='utf-8'))
        const = next(n for n in tree.body if isinstance(n, ast.Assign)
                     and getattr(n.targets[0], 'id', '') == 'BREACH_TOLERANCE')
        fn = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == 'breach_lines')
        namespace = {}
        exec(compile(ast.fix_missing_locations(ast.Module(body=[const, fn], type_ignores=[])),
                     '<seed>', 'exec'), namespace)
        breach_lines = namespace['breach_lines']
        limits = [[-0.9, 0.9], [-0.7, 0.7], [-0.9, 0.9]]
        self.assertEqual(breach_lines('x', [-0.9, -0.7, -0.9], [0.9, 0.7, 0.9], limits,
                                       [['', '']] * 3), [])
        self.assertEqual(breach_lines('x', [-0.9001, -0.7, -0.9], [0.9, 0.7, 0.9], limits,
                                       [['', '']] * 3), [])
        over = breach_lines('x', [-1.06, -0.7, -0.9], [0.9, 0.7, 0.9], limits, [['', '']] * 3)
        self.assertEqual(len(over), 1)
        self.assertIn('X low', over[0])


class DrawingSeam(unittest.TestCase):
    def test_the_seam_is_consulted_for_this_binding_and_the_fallback_stays_reachable(self):
        body = function_source('_asteroid_prop_lists')
        self.assertIn(f"binding = '{BINDING}'", body)
        self.assertIn('mesh_for(binding)', body)
        self.assertIn('return None', body, 'an unselected row must fall back to the procedural rock')
        rock = function_source('_draw_rock')
        self.assertIn('if prop is not None:', rock)
        self.assertIn('return', rock[rock.index('if prop is not None:'):],
                      'the authored branch must not fall through to the facets')

    def test_an_unselected_row_draws_the_legacy_rock(self):
        """No resolver, so no authored mesh: the seam hands back None and the facets are drawn."""
        body = {'ship_lists': {}}
        method = getattr(SimpleNamespace(ship_lists={}), 'ship_lists')
        self.assertEqual(body['ship_lists'], {})
        self.assertIsNone(_call_asteroid_prop_lists(body), 'no selection must mean the legacy path')
        del method

    def test_the_field_draws_the_prop_once_per_instance_and_keeps_its_own_placement(self):
        body = function_source('_draw_asteroid_field')
        self.assertEqual(body.count('field_placement(e.radius, rng)'), 1)
        self.assertEqual(body.count('self._draw_rock('), 1)
        self.assertIn('for _ in range(40):', body)
        self.assertLess(body.index('field_placement'), body.index('self._draw_rock('),
                        'placement is drawn before the rock, as it always was')

    def test_the_field_geometry_and_gameplay_values_are_untouched(self):
        placement = function_source('field_placement')
        for literal in ('rng.uniform(0, 2 * math.pi)', 'radius * (0.15 + 0.85 * math.sqrt(rng.random()))',
                        'rng.uniform(-60, 60)', 'rng.uniform(12, 46)', 'rng.uniform(0.4, 1.6)',
                        'rng.uniform(0, 360)'):
            self.assertIn(literal, placement, 'the field\'s own numbers are not this batch\'s to move')


class RngParity(unittest.TestCase):
    def test_the_rock_parameter_pass_draws_the_legacy_sequence_in_the_legacy_order(self):
        """Both drawing paths call this before they branch, so the stream cannot diverge."""
        namespace = {}
        source = renderer_source()
        fn = re.search(r'^def rock_params\(s, rng\):.*?(?=\n\ndef |\n\nclass |\Z)', source, re.S | re.M)
        self.assertTrue(fn, 'rock_params must stay module level so a guard can drive it')
        exec(compile(ast.parse('import math\n' + fn.group(0)), '<renderer>', 'exec'), namespace)
        rock_params = namespace['rock_params']
        for seed in (1, 7, 99):
            with self.subTest(seed=seed):
                driven = random.Random(seed)
                base, subs = rock_params(10.0, driven)
                # Reconstruct the legacy sequence independently - colour, sub-rock count, then per
                # sub-rock three jitters, one size for the first only, eight corner radii and six
                # bulge radii - and compare where the two streams end up.
                expected = random.Random(seed)
                self.assertEqual(len(base), LEGACY_DRAWS['colour'])
                expected.uniform(-0.08, 0.08)
                expected.uniform(-0.08, 0.06)
                expected.uniform(-0.06, 0.06)
                m = expected.randint(2, 4)
                self.assertEqual(len(subs), m)
                for k in range(m):
                    expected.uniform(-0.25, 0.25)
                    expected.uniform(-0.18, 0.18)
                    expected.uniform(-0.25, 0.25)
                    if k == 0:
                        expected.uniform(0.6, 0.8)
                    for index in range(LEGACY_DRAWS['radii']):
                        if index < 8:
                            expected.uniform(0.75, 1.25)
                        else:
                            expected.uniform(0.9, 1.3)
                self.assertEqual(driven.random(), expected.random(),
                                 'the two streams must be in the same place after one rock')

    def test_the_layout_is_identical_whichever_path_draws_the_rock(self):
        """Drive the field's alternating loop twice with the same seed: placements must match."""
        namespace = {}
        source = renderer_source()
        for name in ('field_placement', 'rock_params'):
            fn = re.search(rf'^def {name}\([^)]*\):.*?(?=\n\ndef |\n\nclass |\Z)', source, re.S | re.M)
            self.assertTrue(fn, name)
            exec(compile(ast.parse('import math\n' + fn.group(0)), '<renderer>', 'exec'), namespace)
        placement = namespace['field_placement']
        rock_params = namespace['rock_params']
        radius = 260.0

        def run():
            rng = random.Random(4242)
            out = []
            for _ in range(40):
                x, y, z, s, angle = placement(radius, rng)
                base, subs = rock_params(s, rng)   # consumed by *both* paths before the branch
                out.append((round(x, 9), round(y, 9), round(z, 9), round(s, 9), round(angle, 9),
                            len(subs)))
            return out

        self.assertEqual(run(), run())
        # ...and the placements do not depend on the rock at all: they are a function of the stream,
        # which both paths advance identically. Draw the facets' radii or not, the layout is the same.
        self.assertTrue(all(len(row) == 6 for row in run()))


def _call_asteroid_prop_lists(fake_self):
    """Call the renderer's seam helper on a stand-in object, with no resolver and no GL context."""
    from render.renderer import Renderer
    return Renderer._asteroid_prop_lists(fake_self)


class BatchRecords(unittest.TestCase):
    def test_the_sheet_carries_exactly_the_one_row_and_its_own_numbers(self):
        spec = load(SPEC)
        self.assertEqual(spec['batch'], 's06-b5-environment')
        self.assertEqual(spec['status'], BATCH_STATUS)
        self.assertEqual(spec['appearance_decision'], APPEARANCE_DECISION)
        self.assertIn('not an approval record', spec['note'])
        self.assertEqual([a['binding'] for a in spec['assets']], [BINDING])
        row = spec['assets'][0]
        self.assertEqual(row['identifier'], IDENTIFIER)
        # The sheet carries the box as [lo, hi] vectors; this guard states it per axis, so the
        # comparison is transposed - the same two spellings the B4 sheet and its guard use.
        self.assertEqual(tuple(zip(*[tuple(a) for a in row['envelope']])), ENVELOPE)
        self.assertEqual(row['min_length'], MIN_LENGTH)
        self.assertEqual(row['seed'], SEED)
        self.assertEqual(row['seed_arg'], f'--asset {BINDING}')

    def test_the_sidecar_agrees_and_the_row_is_not_selectable(self):
        record = load(SIDECAR)
        self.assertEqual(record['binding'], BINDING)
        self.assertEqual(record['status'], BATCH_STATUS)
        self.assertEqual(record['appearance_decision'], APPEARANCE_DECISION)
        # An appearance approval is not a landing: these two stay untouched by it.
        self.assertIsNone(record['owner_decision'])
        self.assertIs(record['activation'], False)
        self.assertFalse(record['activation'])
        self.assertIsNone(record['owner_decision'])
        registry = load(ROOT / 'assets/models/registry.json')
        status = {b['binding']: b['status'] for b in registry['bindings']}
        # The registry does carry this row, and says `authoring_pending`: the environment rows were
        # listed by the S01 inventory as a family, not invented here. Authored is not selected, so
        # what the guard checks is that the status is still the pending one and that nothing selects
        # it in production.
        self.assertEqual(status[BINDING], 'authoring_pending')
        pipeline = load(ROOT / 'art/manifests/pipeline.json')
        self.assertNotIn(BINDING, {a['binding'] for a in pipeline['assets']})
        approvals = load(ROOT / 'art/manifests/approvals.json')
        self.assertNotIn(IDENTIFIER, json.dumps(approvals['approved_assets']))

    def test_the_wrapper_carries_the_unit_envelope_and_the_props_own_tighter_caps(self):
        text = (ROOT / 'tools/art/gen_export_wrappers.py').read_text(encoding='utf-8')
        entry = re.search(r"ASSETS\['shared_asteroid_field'\] = \((.*?)\)\n", text, re.S)
        self.assertTrue(entry, 'the wrapper table must carry the row')
        declaration = entry.group(1)
        for token in ('(-0.58, 0.58)', '(-0.46, 0.46)', '(-0.58, 0.58)', '0.9', '600', '500',
                      '120_000'):
            self.assertIn(token, declaration, token)
        wrapper = (ROOT / f'tools/art/export_{IDENTIFIER}.py').read_text(encoding='utf-8')
        self.assertIn('ENVELOPE = ((-0.58, 0.58), (-0.46, 0.46), (-0.58, 0.58))', wrapper)
        self.assertIn('MIN_LENGTH = 0.9', wrapper)
        self.assertIn('MIN_TRIANGLES = 120', wrapper)
        self.assertIn('MAX_TRIANGLES = 600', wrapper)
        self.assertIn('MAX_VERTICES = 500', wrapper)

    def test_the_small_prop_class_is_declared_and_is_not_a_blanket_relaxation(self):
        """A declared class, not a lowered floor.

        The strong statement is stronger than "only this row went below 1,800": a wrapper outside the
        class is generated **byte for byte** as it was before the class existed, so every already
        approved record's export-script hash stays valid. That is asserted here, together with the
        fact that exactly one wrapper declares anything of its own.
        """
        generator = (ROOT / 'tools/art/gen_export_wrappers.py').read_text(encoding='utf-8')
        self.assertIn("MIN_TRIANGLES = {'shared_asteroid_field': 120}", generator)
        self.assertIn('FLOOR_DEFAULT_ASSERTION = ("    assert 1_800 < asset', generator)
        declared, unfloored = [], []
        for path in sorted((ROOT / 'tools/art').glob('export_*.py')):
            text = path.read_text(encoding='utf-8')
            match = re.search(r'^MIN_TRIANGLES = (\d+)$', text, re.M)
            if match:
                declared.append((path.name, int(match.group(1))))
            elif '        assert 1_800 < asset[' in text:
                unfloored.append(path.name)
            else:
                unfloored.append(path.name)
        self.assertEqual(declared, [('export_shared_asteroid_field.py', 120)],
                         'the class is declared per asset; nothing else may declare a floor')
        wrappers = sorted((ROOT / 'tools/art').glob('export_*.py'))
        self.assertEqual(len(unfloored), len(wrappers) - 1,
                         'every other wrapper keeps the 1_800 floor: the 62 the template generates '
                         'plus the two that predate it')
        policy = load(ROOT / 'art/manifests/pipeline_policy.json')
        entry = next(d for d in policy['decision_log']
                     if d['id'] == 's06-small-prop-class-2026-10-17')
        self.assertEqual(entry['owner_wording'], 'option 1')
        self.assertTrue(entry['not_authorized'])

    def test_the_scope_decision_is_recorded_and_names_what_it_does_not_authorize(self):
        policy = load(ROOT / 'art/manifests/pipeline_policy.json')
        entry = next(d for d in policy['decision_log'] if d['id'] == 's06-b5-scope-2026-10-17')
        self.assertEqual(entry['owner_wording'], 'go with recomendate way')
        self.assertTrue(entry['not_authorized'])
        text = ' '.join(entry['not_authorized']).lower()
        for word in ('texture', 'planet shader', 'landing'):
            self.assertIn(word, text)
        self.assertNotIn('revision', entry, 'a scope decision is not an appearance approval')


